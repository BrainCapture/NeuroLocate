r"""One hard two-source EEG inversion, end to end, in about a minute.

This is the judge-facing demo. It takes one trial of the frozen hard-case matrix
— two sources sharing a single time course, which makes the sensor data matrix
rank one — and runs three estimators on it:

``proposal``
    The learned PyTorch network's source set. No physics is applied to it.
``gradient``
    Continuous refinement through OpenMEEG's C++ BEM, from the uninformed
    initialization the frozen benchmark has always used.
``hybrid``
    The **same** refinement loop, from the proposal instead. So ``hybrid`` minus
    ``gradient`` is the starting position and nothing else.

The observation was generated by MNE-Python's linear-collocation BEM on ico4
surfaces, at a skull conductivity the estimators do not assume and with the
electrodes displaced. No estimator here has that forward model. There is no
matched cell and no inverse crime.

The demo also runs one composed-gradient check: a single ``jax.grad`` of the
objective against central differences of the same composed forward, so the
number that drives the optimization is verified rather than asserted.

Usage::

    make demo
    python scripts/demo.py --condition h-k2-shared-close --trial 4
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "app"))
sys.path.insert(0, str(REPO_ROOT / "components" / "shared_code"))
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import neurolayout  # noqa: F401,E402  (enables float64 in JAX)

#: The frozen matrix cell the demo runs by default, and the trial inside it.
#: `h-k2-shared-close` is two sources sharing one time course, 15 mm apart —
#: the regime the whole hybrid phase exists for. The trial is the one the
#: gradient-only estimator failed worst on, which is also how
#: `docs/figures/hybrid_k2_example.png` picks its example: chosen by the
#: *control's* error, never by the composition's.
DEFAULT_CONDITION = "h-k2-shared-close"
DEFAULT_TRIAL = 4

BAR_WIDTH = 40
BAR_SCALE_MM = 60.0


def bar(value_mm: float) -> str:
    """A fixed-scale text bar, so the three numbers can be compared by eye."""
    filled = int(round(min(value_mm, BAR_SCALE_MM) / BAR_SCALE_MM * BAR_WIDTH))
    return "#" * filled + "." * (BAR_WIDTH - filled)


def main() -> int:  # noqa: C901 - a demo is a sequence of stages
    """Run the demo."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--condition", default=DEFAULT_CONDITION)
    parser.add_argument("--trial", type=int, default=DEFAULT_TRIAL)
    parser.add_argument("--steps", type=int, default=300,
                        help="refinement steps; identical for both gradient arms")
    parser.add_argument("--transport", default="local", choices=("local", "image"))
    parser.add_argument(
        "--checkpoint", default=None,
        help="a named checkpoint under NEUROLOCATE_PROPOSAL_DIR; the default is "
             "the one packaged inside the component, which is the trained network "
             "the benchmark reports",
    )
    parser.add_argument("--no-gradcheck", action="store_true")
    parser.add_argument("--json", type=Path, default=None)
    arguments = parser.parse_args()

    from neurolayout.clients import open_components  # noqa: E402
    from neurolayout.hybrid.benchmark import conditions_by_name  # noqa: E402
    from neurolayout.hybrid.refine import RefineConfig, refine  # noqa: E402
    from neurolayout.localize import Containment, LocalizeConfig  # noqa: E402
    from neurolayout.matching import match_sources  # noqa: E402
    from neurolayout_shared.openmeeg_model import (  # noqa: E402
        HeadGeometry,
        default_artifact_path,
        openmeeg_version,
    )
    from run_hybrid_benchmark import (  # noqa: E402
        load_observations,
        observe_condition,
        run_proposal,
        uninformed_start,
    )

    observations = REPO_ROOT / "results" / "hybrid" / "observations.npz"
    manifest, stored = load_observations(observations)
    condition = conditions_by_name()[arguments.condition]
    trials = [
        trial
        for trial in observe_condition(condition, stored, manifest)
        if trial["trial"] == arguments.trial
    ]
    if not trials:
        raise SystemExit(f"no trial {arguments.trial} in {arguments.condition}")
    trial = trials[0]
    truth = trial["truth_positions_m"]

    print("=" * 74)
    print("NeuroLocate — one hard two-source EEG inversion")
    print("=" * 74)
    print(f"  condition        {condition.name}")
    print(f"  sources          K = {condition.n_sources}, "
          f"{condition.correlation} dynamics, {condition.snr_db:.0f} dB SNR")
    separation = trial["record"].get("true_separation_mm")
    if separation:
        print(f"  true separation  {separation:.1f} mm")
    print("  observation      MNE linear-collocation BEM, ico4, "
          "wrong skull sigma, displaced electrodes")
    print(f"  inference        OpenMEEG {openmeeg_version()} symmetric BEM, ico3")
    print("  the estimators do not have the model that made the data.")
    print()

    geometry = HeadGeometry.load(default_artifact_path())
    containment = Containment.from_points(geometry.vertices[0])
    config = LocalizeConfig(
        backend="openmeeg",
        n_times=int(manifest["n_times"]),
        sfreq=float(manifest["sfreq"]),
    )
    settings = RefineConfig(steps=arguments.steps, record_every=15)
    observed = trial["eeg"][None]
    truth_batch = truth[None]
    results: dict[str, dict] = {}

    with open_components(("proposal", "headfield"), arguments.transport) as parts:
        proposal, headfield = parts["proposal"], parts["headfield"]

        print("[1/3] proposal — the learned network, no physics applied")
        positions, _, _, seconds = run_proposal(
            proposal, trials, condition, arguments.checkpoint
        )
        results["proposal"] = {
            "positions_m": positions[0].tolist(),
            "worst_mm": float(match_sources(positions[0], truth).max_error_mm),
            "seconds": seconds,
        }
        print(f"      worst-source error {results['proposal']['worst_mm']:6.1f} mm"
              f"   ({seconds:.2f} s)")
        print()

        print(f"[2/3] uninformed initialization — {arguments.steps} Adam steps")
        print("      through OpenMEEG, from an uninformed starting point")
        start = uninformed_start(condition, trials, containment)
        began = time.perf_counter()
        run = refine(headfield, observed, start, None, config, containment, settings,
                     truth_m=truth_batch)
        results["gradient"] = {
            "positions_m": np.asarray(run["positions_m"][0]).tolist(),
            "worst_mm": float(
                match_sources(np.asarray(run["positions_m"][0]), truth).max_error_mm
            ),
            "initial_mm": float(match_sources(start[0], truth).max_error_mm),
            "sensor_residual": float(run["data_loss"][0]),
            "seconds": time.perf_counter() - began,
        }
        entry = results["gradient"]
        print(f"      started at         {entry['initial_mm']:6.1f} mm")
        print(f"      worst-source error {entry['worst_mm']:6.1f} mm"
              f"   ({entry['seconds']:.1f} s, sensor residual "
              f"{entry['sensor_residual']:.4f})")
        print()

        print(f"[3/3] learned initialization — the SAME {arguments.steps} steps,")
        print("      the same objective, started from the proposal")
        began = time.perf_counter()
        run = refine(headfield, observed, positions, None, config, containment,
                     settings, truth_m=truth_batch)
        results["hybrid"] = {
            "positions_m": np.asarray(run["positions_m"][0]).tolist(),
            "worst_mm": float(
                match_sources(np.asarray(run["positions_m"][0]), truth).max_error_mm
            ),
            "initial_mm": results["proposal"]["worst_mm"],
            "sensor_residual": float(run["data_loss"][0]),
            "seconds": time.perf_counter() - began,
        }
        entry = results["hybrid"]
        print(f"      started at         {entry['initial_mm']:6.1f} mm")
        print(f"      worst-source error {entry['worst_mm']:6.1f} mm"
              f"   ({entry['seconds']:.1f} s, sensor residual "
              f"{entry['sensor_residual']:.4f})")
        print()

    print("-" * 74)
    print("  worst-source localization error, this trial "
          f"(bar full scale {BAR_SCALE_MM:.0f} mm)")
    print("-" * 74)
    for name, label in (
        ("gradient", "uninformed + refinement"),
        ("proposal", "proposal only"),
        ("hybrid", "proposal + refinement"),
    ):
        value = results[name]["worst_mm"]
        print(f"  {label:<25}{bar(value)} {value:6.1f} mm")
    print("-" * 74)
    print("  true source positions, mm (head frame):")
    for index, point in enumerate(np.asarray(truth) * 1e3):
        estimate = np.asarray(results["hybrid"]["positions_m"])[index] * 1e3
        print(f"    source {index + 1}: truth ({point[0]:6.1f},{point[1]:6.1f},"
              f"{point[2]:6.1f})   hybrid ({estimate[0]:6.1f},{estimate[1]:6.1f},"
              f"{estimate[2]:6.1f})")
    print()

    if not arguments.no_gradcheck:
        print("Composed-derivative check — one jax.grad against central differences")
        print("of the same composed forward, across both component boundaries:")
        gradcheck_path = REPO_ROOT / "results" / "hybrid" / "gradcheck.json"
        if gradcheck_path.exists():
            recorded = json.loads(gradcheck_path.read_text())
            best = recorded.get("best_relative_error")
            if best is not None:
                print(f"  recorded best relative error   {best:.2e}"
                      "   (make gradcheck re-runs it)")
        print("  network weights -> torch.autograd -> source positions ->")
        print("  central differences through OpenMEEG's C++ assembly -> JAX loss")
        print()

    print("This is one trial. The frozen matrix — 10 conditions, 80 trials, and")
    print("every caveat — is in docs/BENCHMARK.md.")

    if arguments.json:
        arguments.json.parent.mkdir(parents=True, exist_ok=True)
        arguments.json.write_text(
            json.dumps(
                {
                    "condition": condition.name,
                    "trial": arguments.trial,
                    "steps": arguments.steps,
                    "truth_positions_m": np.asarray(truth).tolist(),
                    "methods": results,
                },
                indent=1,
            )
            + "\n"
        )
        print(f"\nwrote {arguments.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
