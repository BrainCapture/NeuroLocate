r"""The training forward models, and the gain bank they produce.

Training a global proposal network needs hundreds of thousands of forward
solutions at *continuous* source positions. Doing that naively is one OpenMEEG
assembly per training sample forever. Two facts make it a one-off cost instead.

**The expensive half does not depend on the source.** The symmetric BEM gives

.. math::  G = R \, S(e) \, A(\sigma)^{-1} \, D(p)

and only ``D`` depends on the dipole. So the source term is assembled **once**
per position and every head model in the training distribution is then a matrix
product against it. The factorization is exact — it is a regrouping of the
symmetric BEM's own linear algebra, not an approximation — and here it is what
gives one set of sources many head models for the price of one assembly.

**The map is linear in the moment.** A position's gain is ``[C, 3]``. Every
orientation, amplitude and time course a training sample could want is a
contraction against it, done on the fly in the data loader. So the bank stores
gains, not EEG, and one bank serves an unbounded number of training samples.

What the bank is *not*
----------------------
It is not an interpolant and it is not a grid. Every stored column is a real
``DipSourceMat`` assembly at a real continuous position — the same call the
optimizer makes at inference. The positions are drawn from the cortical surface
with a normal-direction jitter, so they lie **off** every source space in this
project, including the ico5 space the benchmark's truths are drawn between. A
network trained on this bank cannot learn to snap to a candidate, because there
are no candidates.

The training distribution is not the test distribution
------------------------------------------------------
Every variant here is an OpenMEEG symmetric BEM on ico3 fsaverage — the model the
estimator inverts with. The benchmark's observations are generated by MNE-Python's
linear-collocation BEM on ico4 (:mod:`neurolayout.mismatch`), which none of these
variants is. Training on the inference model is exactly what the gradient-only
estimator does when it inverts with it; the mismatch to the generator is what
keeps the measurement honest, and it is unchanged by the proposal network having
seen the inference model many times.

Within that, the variants span the two nuisances the real-data study measured:
skull conductivity, and a *small* residual electrode error. The residual is small
on purpose: an electrode montage that has been registered to an anatomy at all
leaves a few millimetres of scatter, not a centimetre, so a 10 mm montage error
is what a registration step removes rather than what an estimator has to
tolerate.
"""

