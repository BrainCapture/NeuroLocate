r"""The hard-case matrix's design, and the provenance of what it produces.

Three things a benchmark has to get right before any of its numbers mean
anything, and each is easy to break silently:

**The comparison has to be a comparison.** ``k2-distinct``, ``k2-correlated`` and
``k2-shared`` must be handed the *same* sources at the same separations, or the
difference between their rows is a different draw rather than the dynamics.

**The freeze has to bind.** The configuration fingerprint is committed before the
results; the runner refuses observations built for a different matrix, and the
reporter refuses shards produced for one.

**The namespaces have to stay apart.** This matrix must not be able to write
into another benchmark's shard directory, and its condition names must not
collide with another matrix's.
"""

from __future__ import annotations

import numpy as np
import pytest
from neurolayout.benchmark import CONDITIONS as FROZEN_CONDITIONS
from neurolayout.hybrid.benchmark import (
    CONDITIONS,
    CORRELATION_VALUES,
    METHODS,
    HybridCondition,
    conditions_by_name,
    fingerprint,
)

#: The seven cells the phase was defined by. If one of these disappears, the
#: matrix no longer answers the question it was built for.
REQUIRED = (
    ("h-k1", 1, "distinct"),
    ("h-k2-distinct", 2, "distinct"),
    ("h-k2-correlated", 2, "correlated"),
    ("h-k2-shared", 2, "shared"),
    ("h-k4-distinct", 4, "distinct"),
    ("h-k4-correlated", 4, "correlated"),
    ("h-k4-shared", 4, "shared"),
)


def test_the_seven_core_cells_are_present() -> None:
    """The matrix has to contain the cells it was commissioned to run."""
    table = conditions_by_name()
    for name, n_sources, correlation in REQUIRED:
        assert name in table, f"the matrix lost {name}"
        assert table[name].n_sources == n_sources
        assert table[name].correlation == correlation


def test_condition_names_are_unique() -> None:
    """Two cells with one name would silently overwrite each other's shard."""
    assert len(conditions_by_name()) == len(CONDITIONS)


def test_no_condition_name_collides_with_the_frozen_benchmark() -> None:
    """Separate namespaces, so neither sweep can write into the other's shards."""
    frozen = {condition.name for condition in FROZEN_CONDITIONS}
    hybrid = {condition.name for condition in CONDITIONS}
    assert frozen & hybrid == set()
    assert all(name.startswith("h-") for name in hybrid)


def test_there_is_no_matched_cell() -> None:
    """An inverse crime here would answer a different question.

    The frozen benchmark keeps one matched condition as a calibration point, and
    labels it. This matrix compares *estimators* rather than measuring model
    error, so every cell is generated by a forward model none of them has.
    """
    for condition in CONDITIONS:
        assert condition.mismatch != "matched"
        assert condition.mismatch_spec.is_matched is False


def test_cells_that_differ_only_in_dynamics_share_their_sources() -> None:
    """The row-to-row difference has to be the dynamics and nothing else."""
    table = conditions_by_name()
    for group in (
        ("h-k2-distinct", "h-k2-correlated", "h-k2-shared"),
        ("h-k4-distinct", "h-k4-correlated", "h-k4-shared"),
    ):
        seeds = {
            tuple(table[name].truth_seed(trial) for trial in range(8)) for name in group
        }
        assert len(seeds) == 1, f"{group} would be handed different sources"


def test_cells_that_differ_only_in_dynamics_get_different_waveforms() -> None:
    """And the waveform seed *must* differ, or the regimes would be identical."""
    table = conditions_by_name()
    seeds = {
        table[name].waveform_seed(0)
        for name in ("h-k2-distinct", "h-k2-correlated", "h-k2-shared")
    }
    assert len(seeds) == 3


def test_the_snr_excursion_shares_the_sources_of_its_base_cell() -> None:
    """A 10 dB row has to be the same problem at a different noise level."""
    table = conditions_by_name()
    assert table["h-k2-shared-10db"].truth_seed(3) == table["h-k2-shared"].truth_seed(3)
    assert table["h-k2-shared-10db"].noise(3).seed != table["h-k2-shared"].noise(3).seed


def test_a_separation_excursion_is_a_different_problem() -> None:
    """`close` is a different band, so it must draw different sources."""
    table = conditions_by_name()
    assert (
        table["h-k2-shared-close"].truth_seed(0) != table["h-k2-shared"].truth_seed(0)
    )


def test_shared_means_a_cosine_of_exactly_one() -> None:
    """The regime labels have to mean what the document says they mean."""
    assert CORRELATION_VALUES["shared"] == 1.0
    assert CORRELATION_VALUES["distinct"] is None
    assert 0.0 < CORRELATION_VALUES["correlated"] < 1.0


def test_seeds_are_stable_across_processes() -> None:
    """A benchmark seeded with `hash()` would not be reproducible at all."""
    condition = conditions_by_name()["h-k4-shared"]
    assert condition.truth_seed(2) == condition.truth_seed(2)
    assert condition.truth_seed(2) != condition.truth_seed(3)
    assert isinstance(condition.truth_seed(0), int)


def test_the_fingerprint_covers_the_matrix_and_the_methods() -> None:
    """The freeze has to bind to everything that could change a result."""
    original = fingerprint()
    assert len(original) == 64
    assert fingerprint() == original

    changed = tuple(CONDITIONS) + (
        HybridCondition("h-extra", 2, "shared", separation="moderate"),
    )
    assert fingerprint(changed) != original


def test_the_method_list_names_all_five_mandated_arms() -> None:
    """The ablation is the deliverable; a missing arm is a missing answer."""
    for method in ("rapmusic", "gradient", "proposal", "hybrid", "hybrid_stopgrad"):
        assert method in METHODS


@pytest.mark.parametrize("condition", CONDITIONS, ids=lambda c: c.name)
def test_every_cell_is_runnable(condition: HybridCondition) -> None:
    """Reject a cell that cannot be run at import time rather than at hour three."""
    assert condition.n_trials > 0
    assert (condition.separation is None) == (condition.n_sources == 1)
    assert condition.correlation_value is None or 0.0 <= condition.correlation_value <= 1.0
    noise = condition.noise(0)
    assert noise.snr_db == condition.snr_db
    assert 0 <= noise.seed < 2**31


def test_one_source_cannot_be_correlated_with_itself() -> None:
    """A K=1 cell labelled `shared` would be a meaningless row."""
    with pytest.raises(ValueError, match="nothing to correlate"):
        HybridCondition("h-bad", 1, "shared")


def test_a_multi_source_cell_needs_a_separation_regime() -> None:
    """Without one the draw is unconstrained and the row is uninterpretable."""
    with pytest.raises(ValueError, match="needs a separation regime"):
        HybridCondition("h-bad", 2, "shared")


def test_the_trial_count_is_what_the_report_expects() -> None:
    """The reporter refuses a partial matrix unless asked; this is that total."""
    assert sum(condition.n_trials for condition in CONDITIONS) == 80
    assert len(CONDITIONS) == 10


def test_initialization_seeds_are_shared_by_comparable_cells() -> None:
    """`gradient` must start from the same point in every dynamics regime."""
    table = conditions_by_name()
    seeds = {
        table[name].initialization_seed(1)
        for name in ("h-k4-distinct", "h-k4-correlated", "h-k4-shared")
    }
    assert len(seeds) == 1


def test_the_noise_realization_is_shared_by_comparable_cells() -> None:
    """Two cells at the same SNR and K see the same noise, so rows are paired."""
    table = conditions_by_name()
    seeds = {
        table[name].noise(0).seed
        for name in ("h-k2-distinct", "h-k2-correlated", "h-k2-shared")
    }
    assert len(seeds) == 1


def test_separation_bands_do_not_overlap_where_it_matters() -> None:
    """`close` and `moderate` have to be different regimes, not the same one."""
    from neurolayout.benchmark import SEPARATION_REGIMES

    close_low, close_high = SEPARATION_REGIMES["close"]
    moderate_low, _ = SEPARATION_REGIMES["moderate"]
    assert close_high <= moderate_low
    assert close_low < close_high


def test_reported_positions_are_never_on_the_source_space_grid() -> None:
    """Truths are off grid by construction, so no dictionary method can be exact."""
    from neurolayout.benchmark import offgrid_truth

    rng = np.random.default_rng(0)
    space = rng.standard_normal((200, 3)) * 0.03
    normals = rng.standard_normal((200, 3))
    normals /= np.linalg.norm(normals, axis=1, keepdims=True)
    for index in range(10):
        position, normal, offgrid = offgrid_truth(space, normals, index, 0.5)
        assert offgrid > 0.0
        assert np.linalg.norm(position - space[index]) > 0.0
        np.testing.assert_allclose(np.linalg.norm(normal), 1.0)
